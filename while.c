#include <stdio.h>

int main(){
    int i = 0, soma = 0;
    while (i < 10)
    {       
        printf("%d ", i);
        i++;
    }

    printf("\n");
    printf("----------------------------------------------------------------------\n");

    i = 11;
    while(i < 15){
        printf("%d ", i);
        i++;   
    }

    printf("\n");
    printf("----------------------------------------------------------------------\n");

    i = 4;
    while(i >= 0){
        printf("%d ", i);
        i--;
    }

    printf("\n");
    printf("----------------------------------------------------------------------\n");

    i = 0;
    soma = 0;

    while(i <= 10){
        printf("%d ", i);
        soma += i;
        i++;
        i++;
    }
    printf("Soma: %d", soma);

    printf("\n");
    printf("----------------------------------------------------------------------\n");
    return 0;
}